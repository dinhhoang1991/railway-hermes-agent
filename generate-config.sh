    workspaceContext: false
    skills:
      enabled: false
    toolBash: false
    toolJobs: false

- id: sessions
  name: '@deepseek-ai/dsh-session-persistence-jsonl'
  config:
    root: !!js process.env.DSH_SESSION_ROOT ?? '$ROOT_DIR/sessions'

- id: telegram-tool
  name: '$TELEGRAM_TS'

- id: opencv-tool
  name: '$OPENCV_TS'

- id: iot-http-tool
  name: '$IOT_HTTP_TS'

- id: iot-mqtt-tool
  name: '$IOT_MQTT_TS'
