  name: '@deepseek-ai/dsh-llm-deepseek'
  config:
    apiKeyEnv: DEEPSEEK_API_KEY
    models:
      - id: !!js process.env.DSH_MODEL ?? 'deepseek-v4-pro'
        contextWindow: 1000000

- id: fs-local
  name: '@deepseek-ai/dsh-fs-local'
  config:
    cwd: !!js process.env.DSH_CWD ?? '$ROOT_DIR'

- id: agent-spine
  name: '@deepseek-ai/dsh-agent-spine-demo'
  config:
    persona: |
      Bạn là Senior Software Engineer chuyên hệ thống giám sát an toàn đường sắt Việt Nam, đặc biệt khu vực Cam Ranh - Khánh Hòa.

